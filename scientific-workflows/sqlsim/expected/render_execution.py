from pathlib import Path
import hashlib,json
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

root=Path('/bundle')
r=json.loads((root/'evidence/daemon-run.json').read_text())
a=r['projection']['activities'];assert len(a)==r['activityCount'] and all(x['status']=='completed' for x in a)
a=sorted(a,key=lambda x:x['startedAt']);start=min(x['startedAt'] for x in a)
fig,ax=plt.subplots(figsize=(12,max(4,len(a)*.3)),constrained_layout=True)
colors=plt.get_cmap('tab20')
for i,x in enumerate(a):
    ax.barh(i,x['finishedAt']-x['startedAt'],left=x['startedAt']-start,color=colors(i%20),height=.7)
ax.set_yticks(range(len(a)),[x['activityId'].removeprefix(r['workflowId']+'-') for x in a],fontsize=8)
ax.invert_yaxis();ax.set_xlabel('Observed seconds from first activity start');ax.set_title(root.name+' — measured native daemon execution')
ax.spines[['top','right']].set_visible(False);ax.grid(axis='x',alpha=.2)
fig.savefig(root/'screenshots/current/execution-timeline.png',dpi=150)
current=0;peak=0
for _,delta in sorted([(x['startedAt'],1) for x in a]+[(x['finishedAt'],-1) for x in a]):current+=delta;peak=max(peak,current)
summary={'runId':r['runId'],'imageId':r['imageId'],'completedActivities':len(a),'observedMakespanSeconds':r['projection']['run']['makespanSeconds'],'peakOverlappingActivities':peak,'timingSource':'observed native startedAt/finishedAt; imported predicted times excluded'}
(root/'evidence/execution-summary.json').write_text(json.dumps(summary,indent=2)+'\n')
p=root/'screenshots/current/manifest.json';m=json.loads(p.read_text());m['source']='scientific figures copied from completed daemon outputs; timeline derived from observed native activity times'
m['figures']['execution-timeline.png']=hashlib.sha256((root/'screenshots/current/execution-timeline.png').read_bytes()).hexdigest();m['executionSummary']=summary;p.write_text(json.dumps(m,indent=2,ensure_ascii=False)+'\n')
p=root/'README.md';s=p.read_text().split('\n## Observed parallel execution\n')[0];s=s.replace('Figures below were generated by the completed daemon run, verified against its artifact SHA-256 hashes, and copied without editing. They show actual computed results, not interface mockups.', 'Scientific figures below were generated by the completed daemon run, verified against its artifact SHA-256 hashes, and copied without editing. The execution timeline is derived from observed native activity start/finish times. All figures show measured results.')
s+='\n## Observed parallel execution\n\n'+f"The native run completed {len(a)} activities in **{summary['observedMakespanSeconds']:.2f} seconds**, with **{peak} overlapping activities** at peak. These are execution observations, not a measured speedup against a sequential baseline.\n\n![Measured execution timeline](screenshots/current/execution-timeline.png)\n"
p.write_text(s)
print(json.dumps(summary))
