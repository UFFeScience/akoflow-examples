// Command materialize builds standalone source bundles from canonical workloads.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type scenario struct {
	Module       string          `json:"module"`
	Summary      string          `json:"summary"`
	Inputs       json.RawMessage `json:"inputs"`
	Requirements []string        `json:"requirements"`
	Artifacts    []string        `json:"artifacts"`
}

func main() {
	root := flag.String("root", ".", "examples checkout")
	check := flag.Bool("check", false, "verify generated files without changing them")
	flag.Parse()
	if err := materialize(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func materialize(root string, check bool) error {
	data, err := os.ReadFile(filepath.Join(root, "workloads/scenarios.json"))
	if err != nil {
		return err
	}
	scenarios := map[string]scenario{}
	if err := json.Unmarshal(data, &scenarios); err != nil {
		return err
	}
	core, err := os.ReadFile(filepath.Join(root, "workloads/core.py"))
	if err != nil {
		return err
	}
	for relative, spec := range scenarios {
		module, err := os.ReadFile(filepath.Join(root, "workloads", spec.Module+".py"))
		if err != nil {
			return err
		}
		bundle := filepath.Join(root, relative)
		script := "# Generated by go run tools/materialize/main.go; edit workloads/ instead.\n" + string(core) + "\n" + string(module) + "\nif __name__ == '__main__':\n    run_stage()\n"
		input := append(append([]byte{}, spec.Inputs...), '\n')
		for name, content := range map[string][]byte{"scripts/run_showcase.py": []byte(script), "data/workload.json": input} {
			target := filepath.Join(bundle, name)
			if check {
				actual, err := os.ReadFile(target)
				if err != nil || string(actual) != string(content) {
					return fmt.Errorf("stale generated file: %s", target)
				}
			} else if err := os.WriteFile(target, content, 0644); err != nil {
				return err
			}
		}
		if check {
			continue
		}
		requirements := strings.Join(spec.Requirements, "\n") + "\n"
		if len(spec.Requirements) > 0 {
			if err := os.WriteFile(filepath.Join(bundle, "requirements.txt"), []byte(requirements), 0644); err != nil {
				return err
			}
		}
		prepare := `#!/bin/sh
set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
command -v go >/dev/null || { echo 'Install Go before running this example.' >&2; exit 1; }
go -C "$root/../.." mod download
command -v python3 >/dev/null || { echo 'Install Python 3 before running this example.' >&2; exit 1; }
if [ -s "$root/requirements.txt" ]; then
  python3 -m venv "$root/.venv"
  "$root/.venv/bin/python" -m pip install -r "$root/requirements.txt"
else
  printf 'No additional Python packages are required. Run ./run.sh.\n'
fi
if [ "${AKOFLOW_LOCAL_CONTAINER:-0}" = 1 ]; then
  go run "$root/../../tools/showcase/main.go" -root "$root" -prepare-container
fi
`
		if err := os.WriteFile(filepath.Join(bundle, "prepare.sh"), []byte(prepare), 0755); err != nil {
			return err
		}

		configPath := filepath.Join(bundle, "data/input.json")
		raw, err := os.ReadFile(configPath)
		if err != nil {
			return err
		}
		var config map[string]any
		if err := json.Unmarshal(raw, &config); err != nil {
			return err
		}
		config["validationMode"] = "local-workload"
		config["localProfile"] = spec.Summary
		if len(spec.Artifacts) > 0 {
			config["artifacts"] = spec.Artifacts
			path := filepath.Join(bundle, "expected/manifest.json")
			raw, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			var expected map[string]any
			if err := json.Unmarshal(raw, &expected); err != nil {
				return err
			}
			expected["artifacts"] = spec.Artifacts
			bytes, err := json.MarshalIndent(expected, "", "  ")
			if err != nil {
				return err
			}
			if err := os.WriteFile(path, append(bytes, '\n'), 0644); err != nil {
				return err
			}
		}
		encoded, err := json.MarshalIndent(config, "", "  ")
		if err != nil {
			return err
		}
		if err := os.WriteFile(configPath, append(encoded, '\n'), 0644); err != nil {
			return err
		}
		dockerfile := filepath.Join(bundle, "docker/Dockerfile")
		docker := "FROM python:3.12-slim\nWORKDIR /app\n"
		if len(spec.Requirements) > 0 {
			docker += "COPY requirements.txt /app/requirements.txt\nRUN python -m pip install --no-cache-dir -r /app/requirements.txt\n"
		}
		docker += "COPY data/input.json /app/scenario.json\nCOPY scripts/run_showcase.py /app/run_showcase.py\nCOPY data/ /app/data/\n"
		if err := os.WriteFile(dockerfile, []byte(docker), 0644); err != nil {
			return err
		}

		readmePath := filepath.Join(bundle, "README.md")
		readme, err := os.ReadFile(readmePath)
		if err != nil {
			return err
		}
		paragraphs := strings.SplitN(string(readme), "\n\n", 3)
		if len(paragraphs) == 3 {
			paragraphs[1] = spec.Summary
			text := strings.Join(paragraphs, "\n\n")
			if !strings.Contains(text, "## Fresh local checkout") {
				command := "## Fresh local checkout\n\nRequires Go and Python 3.12+. Run this command from the directory in which you keep your repositories:\n\n```sh\ngit clone https://github.com/UFFeScience/akoflow-examples.git\ncd akoflow-examples/" + relative + "\n./prepare.sh && ./run.sh\n```\n\n`prepare.sh` downloads the pinned Python packages (when required) and Go module once. `run.sh` then executes the local stages offline in dependency waves. Results are in `outputs/`; inspect `manifest.json`, `dag-validation.json`, and each `stage-<name>.json`. Independent branches run concurrently.\n\n"
				parts := strings.SplitN(text, "\n\n", 3)
				if len(parts) == 3 {
					text = parts[0] + "\n\n" + parts[1] + "\n\n" + command + parts[2]
				}
			}
			text = strings.ReplaceAll(text, "An AkôFlow orchestration contract fixture.", "A local CPU workload.")
			if err := os.WriteFile(readmePath, []byte(text), 0644); err != nil {
				return err
			}
		}
	}
	return nil
}
